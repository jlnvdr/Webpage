const translatableNodes = document.querySelectorAll("[data-i18n]");
const ariaTranslatableNodes = document.querySelectorAll("[data-i18n-aria]");
const languageButtons = document.querySelectorAll(".lang-btn");
const storageKey = "officina-adler-language";
const galleryImages = [
    "assets/gallery/gallery-engine.svg",
    "assets/gallery/gallery-lift.svg",
    "assets/gallery/gallery-detail.svg",
    "assets/gallery/gallery-tires.svg",
    "assets/gallery/Home_winter.jpg"
];

function initGallery() {
    const stageImage = document.querySelector(".gallery-stage-image");
    const stageCount = document.querySelector(".gallery-stage-count");
    const thumbsRoot = document.querySelector(".gallery-thumbs");

    if (!stageImage || !stageCount || !thumbsRoot || galleryImages.length === 0) {
        return;
    }

    let activeIndex = 0;
    let rotationHandle;

    function updateGallery(index) {
        activeIndex = index;
        stageImage.src = galleryImages[index];
        stageImage.alt = `Werkstattgalerie Bild ${index + 1}`;
        stageCount.textContent = `${index + 1} / ${galleryImages.length}`;

        thumbsRoot.querySelectorAll(".gallery-thumb").forEach((thumb, thumbIndex) => {
            thumb.classList.toggle("is-active", thumbIndex === index);
        });
    }

    function restartRotation() {
        window.clearInterval(rotationHandle);
        rotationHandle = window.setInterval(() => {
            updateGallery((activeIndex + 1) % galleryImages.length);
        }, 4000);
    }

    galleryImages.forEach((imagePath, index) => {
        const button = document.createElement("button");
        const image = document.createElement("img");

        button.type = "button";
        button.className = "gallery-thumb";
        button.setAttribute("aria-label", `Galeriebild ${index + 1} anzeigen`);

        image.src = imagePath;
        image.alt = "";

        button.appendChild(image);
        button.addEventListener("click", () => {
            updateGallery(index);
            restartRotation();
        });

        thumbsRoot.appendChild(button);
    });

    updateGallery(0);
    restartRotation();

    thumbsRoot.addEventListener("mouseenter", () => window.clearInterval(rotationHandle));
    thumbsRoot.addEventListener("mouseleave", restartRotation);
}

function applyLanguage(language) {
    const dictionary = translations[language] || translations.de;

    document.documentElement.lang = language;

    translatableNodes.forEach((node) => {
        const key = node.dataset.i18n;
        const text = dictionary[key];

        if (!text) {
            return;
        }

        node.innerHTML = text;
    });

    ariaTranslatableNodes.forEach((node) => {
        const key = node.dataset.i18nAria;
        const text = dictionary[key];

        if (!text) {
            return;
        }

        node.setAttribute("aria-label", text);
    });

    languageButtons.forEach((button) => {
        button.classList.toggle("is-active", button.dataset.lang === language);
    });

    window.localStorage.setItem(storageKey, language);
}

languageButtons.forEach((button) => {
    button.addEventListener("click", () => {
        applyLanguage(button.dataset.lang);
    });
});

const preferredLanguage = window.localStorage.getItem(storageKey);
applyLanguage(preferredLanguage && translations[preferredLanguage] ? preferredLanguage : "de");
initGallery();